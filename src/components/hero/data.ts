export function preloadImages(projects: any[], mode: string) {
  return Promise.all(
    projects
      .slice(0, 4)
      .map((p) => ('desktop' === mode ? p.desktop : p.mobile))
      .filter((src) => !!src)
      .map(
(src) =>
  new Promise<void>((resolve) => {
    const img = new Image();
    img.src = src;
    img.decode?.().then(
      () => resolve(),
      () => resolve(),
    ) ?? resolve();
  }),
      ),
  );
}

